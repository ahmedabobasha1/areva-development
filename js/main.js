const counters = document.querySelectorAll("[data-count]");
if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const countObs = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      const target = Number(el.dataset.count);
      const start = performance.now();
      const duration = 900;
      function tick(now) {
        const p = Math.min(1, (now - start) / duration);
        el.textContent = String(Math.round(target * (1 - Math.pow(1 - p, 3))));
        if (p < 1) requestAnimationFrame(tick);
      }
      requestAnimationFrame(tick);
      countObs.unobserve(el);
    });
  }, { threshold: 0.6 });
  counters.forEach((el) => countObs.observe(el));
}

const form = document.getElementById("enquiry");
const errorEl = document.getElementById("form-error");
const successEl = document.getElementById("form-success");

function validEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}

form.addEventListener("submit", (event) => {
  event.preventDefault();
  if (form.website && form.website.value) return;
  errorEl.hidden = true;
  successEl.hidden = true;
  const data = new FormData(form);
  const name = String(data.get("name") || "").trim();
  const phone = String(data.get("phone") || "").replace(/\s/g, "");
  const email = String(data.get("email") || "").trim();
  const interest = String(data.get("interest") || "");
  let ok = true;
  form.querySelectorAll(".field").forEach((field) => field.classList.remove("is-invalid"));
  if (name.length < 2) {
    form.querySelector('[name="name"]').closest(".field").classList.add("is-invalid");
    ok = false;
  }
  if (phone.replace(/\D/g, "").length < 8) {
    form.querySelector('[name="phone"]').closest(".field").classList.add("is-invalid");
    ok = false;
  }
  if (!validEmail(email)) {
    form.querySelector('[name="email"]').closest(".field").classList.add("is-invalid");
    ok = false;
  }
  if (!ok) {
    errorEl.textContent = lang === "ar" ? ar["form.err"] : "Please check your name, phone number and email.";
    errorEl.hidden = false;
    return;
  }
  const body = `Name: ${name}\nPhone: +20${phone}\nEmail: ${email}\nInterested in: ${interest}`;
  if (ENQUIRY_EMAIL) {
    window.location.href = `mailto:${ENQUIRY_EMAIL}?subject=${encodeURIComponent("AREVA enquiry — " + interest)}&body=${encodeURIComponent(body)}`;
    successEl.textContent = lang === "ar" ? ar["form.okMail"] : "Thank you. Your message is ready for the sales team.";
  } else {
    successEl.textContent = lang === "ar"
      ? ar["form.ok"]
      : "Thank you, " + name + ". Call 19030 and our sales team will continue this enquiry about " + interest + ".";
  }
  successEl.hidden = false;
  form.reset();
});

