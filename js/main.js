function rememberEnglish() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (!el.dataset.en) el.dataset.en = el.textContent.trim();
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    if (!el.dataset.enAlt) el.dataset.enAlt = el.getAttribute("alt") || "";
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    if (!el.dataset.enAria) el.dataset.enAria = el.getAttribute("aria-label") || "";
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    if (!el.dataset.enPh) el.dataset.enPh = el.getAttribute("placeholder") || "";
  });
}

function applyLanguage(next) {
  lang = next;
  document.documentElement.lang = next === "ar" ? "ar" : "en";
  document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
  document.title = titles[next];
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", descriptions[next]);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    el.textContent = next === "ar" ? (ar[key] || el.dataset.en) : el.dataset.en;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.dataset.i18nAlt;
    el.setAttribute("alt", next === "ar" ? (ar[key] || el.dataset.enAlt) : el.dataset.enAlt);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    el.setAttribute("aria-label", next === "ar" ? (ar[key] || el.dataset.enAria) : el.dataset.enAria);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    el.setAttribute("placeholder", next === "ar" ? (ar[key] || el.dataset.enPh) : el.dataset.enPh);
  });
  langBtn.textContent = next === "ar" ? "EN" : "AR";
  langBtn.setAttribute("aria-label", next === "ar" ? "Show the page in English" : "عرض الصفحة بالعربية");
  const nextBtn = document.getElementById("hero-next");
  if (nextBtn) nextBtn.setAttribute("aria-label", next === "ar" ? ar["ui.next"] : "Next highlight");
  try { localStorage.setItem("areva-lang", next); } catch (e) { /* ignore */ }
}

