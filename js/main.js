function setupReveal() {
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const nodes = [...document.querySelectorAll(
    ".portrait-wrap, .story-copy, .stat, .section-head, .project-card, .feature-visual, .feature-copy, .news-photo, .news-card, .message blockquote, .quote-photo, .careers-grid > div, .contact-grid > div, .info-card"
  )];
  if (reduce) return;
  nodes.forEach((el, index) => {
    el.classList.add("reveal");
    el.style.transitionDelay = (index % 4) * 90 + "ms";
  });
  const revealSeen = () => {
    nodes.forEach((el) => {
      if (el.classList.contains("is-in")) return;
      if (el.getBoundingClientRect().top < window.innerHeight - 24) el.classList.add("is-in");
    });
  };
  revealSeen();
  window.addEventListener("scroll", revealSeen, { passive: true });
}
